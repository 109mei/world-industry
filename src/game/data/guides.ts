/**
 * 使い方ガイド。
 *
 * 「やることチュートリアル」（TUTORIAL_STEPS）とは別物。
 * あちらは押す場所を順に指していくもので、こちらは
 * 「その画面で何ができるのか」を読むだけで分かるようにするもの。
 * 買わせたり作らせたりはしない。閉じれば終わりで、設定からいつでも読み返せる。
 */

/** ガイドを出すかどうかを決めるときの、いまの状況 */
export interface GuideContext {
  state: GameState;
  derived: DerivedState;
  tab: NavTab;
  /** ホームの中の切替 */
  homeSub: string;
  /** 地図の中の切替 */
  mapSub: string;
}

export type GuideGroup = 'basic' | 'map' | 'work' | 'money';

export const GUIDE_GROUP_LABEL: Record<GuideGroup, string> = {
  basic: '基本',
  map: '地図と土地',
  work: '生産と研究',
  money: 'お金と商売',
};

export interface GuidePoint {
  /** 見出し（短く） */
  label: string;
  /** 説明（1〜2文） */
  text: string;
}

export interface GuideDef {
  id: string;
  title: string;
  /** 一覧に出す1行の説明 */
  summary: string;
  group: GuideGroup;
  icon: string;
  /** 本文（1要素＝1段落） */
  body: string[];
  /** できること */
  points: GuidePoint[];
  /** 自動で出す条件。満たしたときに1回だけ出る */
  when: (c: GuideContext) => boolean;
}

