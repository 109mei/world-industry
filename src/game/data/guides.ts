export const GUIDE_MAP: Record<string, GuideDef> = Object.fromEntries(GUIDES.map((g) => [g.id, g]));

export function isGuideId(id: string): boolean {
  return Object.prototype.hasOwnProperty.call(GUIDE_MAP, id);
}

/** いま出すべきガイド（まだ読んでいないもののうち、条件を満たした最初の1つ） */
export function nextGuide(c: GuideContext): GuideDef | null {
  if (c.state.settings.guidesOff === true) return null;
  // 全部読み終わっていたら、条件を1つも調べない（描画のたびに呼ばれるため）
  const seenList = c.state.settings.guidesSeen;
  if (seenList && seenList.length >= GUIDES.length) return null;
  // 最初の選択（配色・会社名・本社）が終わるまでは出さない
  if (c.state.settings.themeChosen !== true || c.state.settings.nameChosen !== true || c.state.settings.hqChosen !== true) return null;
  const seen = new Set(c.state.settings.guidesSeen ?? []);
  for (const g of GUIDES) {
    if (seen.has(g.id)) continue;
    let ok = false;
    try {
      ok = g.when(c);
    } catch {
      ok = false;
    }
    if (ok) return g;
  }
  return null;
}
