/**
 * 地図表示用の簡略化した大陸の輪郭（経度, 緯度）。
 * ゲーム用の「それらしい」形で、正確な地理データではない。
 */
export type LonLat = [number, number];

export const MAP_LON_MIN = -170;
export const MAP_LON_MAX = 180;
export const MAP_LAT_MIN = -58;
export const MAP_LAT_MAX = 80;
/** 1度あたりのピクセル */
export const MAP_SCALE = 2.5;
export const MAP_WIDTH = (MAP_LON_MAX - MAP_LON_MIN) * MAP_SCALE;
export const MAP_HEIGHT = (MAP_LAT_MAX - MAP_LAT_MIN) * MAP_SCALE;

export function project(lon: number, lat: number): { x: number; y: number } {
  return { x: (lon - MAP_LON_MIN) * MAP_SCALE, y: (MAP_LAT_MAX - lat) * MAP_SCALE };
}

export function toPath(points: LonLat[]): string {
  return points
    .map(([lon, lat], i) => {
      const { x, y } = project(lon, lat);
      return `${i === 0 ? 'M' : 'L'}${x.toFixed(1)} ${y.toFixed(1)}`;
    })
    .join(' ') + ' Z';
}

